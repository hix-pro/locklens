use anyhow::{Context, Result, bail};
use toml::Value;

use crate::model::{LockFormat, Lockfile, Package};

/// Parses `Cargo.lock`. Workspace members and path dependencies have no
/// source or checksum; they are skipped because their version follows the
/// project's own release cadence rather than a dependency update.
pub fn parse(text: &str) -> Result<Lockfile> {
    let value: Value = toml::from_str(text).context("invalid TOML")?;
    let lockfile_version = value
        .get("version")
        .and_then(Value::as_integer)
        .map(|version| version.to_string());
    let Some(entries) = value.get("package").and_then(Value::as_array) else {
        bail!("no [[package]] entries found");
    };

    let mut packages = Vec::new();
    for entry in entries {
        let Some(name) = entry.get("name").and_then(Value::as_str) else {
            continue;
        };
        let Some(version) = entry.get("version").and_then(Value::as_str) else {
            continue;
        };
        let source = entry.get("source").and_then(Value::as_str);
        let checksum = entry.get("checksum").and_then(Value::as_str);
        if source.is_none() && checksum.is_none() {
            continue;
        }
        let mut package = Package::new(name, version);
        if let Some(source) = source {
            package.add_source(source);
        }
        if let Some(checksum) = checksum {
            package.add_integrity(checksum);
        }
        packages.push(package);
    }

    if packages.is_empty() {
        bail!("no registry or git packages found");
    }
    Ok(Lockfile::new(LockFormat::Cargo, lockfile_version, packages))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_registry_packages_and_skips_local_ones() {
        let text = r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "app"
version = "0.1.0"
dependencies = ["anyhow"]

[[package]]
name = "anyhow"
version = "1.0.95"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "34ac096ce696"

[[package]]
name = "gitdep"
version = "0.2.0"
source = "git+https://github.com/example/gitdep?rev=abc#abc"
"#;
        let lockfile = parse(text).unwrap();
        assert_eq!(lockfile.format, LockFormat::Cargo);
        assert_eq!(lockfile.lockfile_version.as_deref(), Some("4"));
        assert_eq!(lockfile.package_count(), 2);
        assert_eq!(lockfile.packages[0].name, "anyhow");
        assert!(lockfile.packages[0].integrities.contains("34ac096ce696"));
        assert_eq!(lockfile.packages[1].name, "gitdep");
        assert!(
            lockfile.packages[1]
                .sources
                .contains("git+https://github.com/example/gitdep?rev=abc#abc")
        );
    }

    #[test]
    fn rejects_a_lockfile_without_packages() {
        assert!(parse("version = 4\n").is_err());
    }
}
